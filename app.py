def csrf_required(fn):
    @wraps(fn)
    def wrapped(*args, **kwargs):
        sent = request.headers.get('X-CSRF-Token') or request.form.get('csrf_token')
        if not sent or not secrets.compare_digest(sent, session.get('csrf_token', '')):
            return jsonify({'error':'Security token missing or expired. Refresh the page and try again.'}), 400
        return fn(*args, **kwargs)
    return wrapped

def clean_text(value, limit):
    return re.sub(r'[\x00-\x1f\x7f]', '', str(value or '')).strip()[:limit]

def valid_email(value):
    return bool(re.fullmatch(r"[^\s@<>]+@[^\s@<>]+\.[^\s@<>]+", value or ''))

def send_alert_email(alert_id):
    """Runs outside the request thread. SMTP is enabled only when configured in environment."""
    with app.app_context():
        alert = db.session.get(Alert, alert_id)
        contacts = Contact.query.order_by(Contact.id.asc()).all()
        host = os.environ.get('SMTP_HOST'); user = os.environ.get('SMTP_USER')
        password = os.environ.get('SMTP_PASSWORD'); sender = os.environ.get('SMTP_FROM') or user
        if not all([host, user, password, sender]) or not contacts:
            alert.status = 'saved_no_email_config' if contacts else 'saved_no_contacts'
            db.session.commit(); return
        maps = f'https://maps.google.com/?q={alert.latitude},{alert.longitude}' if alert.latitude is not None and alert.longitude is not None else 'Location unavailable; the user did not share coordinates.'
        sent = 0
        for contact in contacts:
            try:
                msg = EmailMessage(); msg['Subject'] = 'SakhiSuraksha SOS Alert'; msg['From'] = sender; msg['To'] = contact.email
                msg.set_content(f"SakhiSuraksha emergency alert\n\nAn SOS was activated using: {alert.trigger}.\nTime (UTC): {alert.created_at.isoformat()}\nLocation: {maps}\n\nThis message was generated by the SakhiSuraksha application. Please try to contact the person and follow local emergency procedures. This application does not automatically contact police or emergency services.")
                with smtplib.SMTP(host, int(os.environ.get('SMTP_PORT', '587')), timeout=12) as server:
                    server.starttls(); server.login(user, password); server.send_message(msg)
                sent += 1
            except Exception as exc:
                app.logger.warning('Email delivery failed for contact %s: %s', contact.id, type(exc).__name__)
        alert.status = f'email_sent_{sent}_of_{len(contacts)}' if sent else 'email_failed'
        db.session.commit()

def start_email(alert_id):
    threading.Thread(target=send_alert_email, args=(alert_id,), daemon=True).start()

